def parse_database_url(default_sqlite_path: Path) -> dict:
    db_url = os.getenv('DATABASE_URL')
    if not db_url:
        return {
            'ENGINE': 'django_prometheus.db.backends.sqlite3',
            'NAME': default_sqlite_path,
        }

    parsed = urlparse(db_url)
    scheme = parsed.scheme.replace('postgres', 'postgresql')
    engine_map = {
        'postgresql': 'django.db.backends.postgresql',
        'mysql': 'django.db.backends.mysql',
        'sqlite': 'django.db.backends.sqlite3',
    }
    engine = engine_map.get(scheme)
    if not engine:
        raise ImproperlyConfigured(
            f"Unsupported database scheme '{parsed.scheme}' in DATABASE_URL"
        )

    if engine.endswith('sqlite3'):
        db_name = parsed.path.lstrip('/') or default_sqlite_path
        return {'ENGINE': engine, 'NAME': db_name}

    db_config: dict[str, object] = {
        'ENGINE': engine,
        'NAME': parsed.path.lstrip('/') or '',
        'USER': parsed.username,
        'PASSWORD': parsed.password,
        'HOST': parsed.hostname,
        'PORT': parsed.port,
    }

    query_options = {
        key.upper(): values[0]
        for key, values in parse_qs(parsed.query).items()
        if values
    }
    if query_options:
        db_config['OPTIONS'] = query_options

    return db_config


