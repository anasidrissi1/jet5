def host_to_origin_regex(host: str) -> str | None:
    host = host.strip()
    if not host or host == '*':
        return None
    if host.startswith('http://') or host.startswith('https://'):
        return rf"^{re.escape(host)}$"

    allow_subdomains = host.startswith('.')
    trimmed = host.lstrip('.')
    if ':' in trimmed:
        hostname, port = trimmed.rsplit(':', 1)
        hostname_pattern = re.escape(hostname)
        return rf"^https?://{hostname_pattern}:{re.escape(port)}$"

    hostname_pattern = re.escape(trimmed)
    if allow_subdomains:
        hostname_pattern = rf"(?:[\w-]+\.)*{hostname_pattern}"
    return rf"^https?://{hostname_pattern}(?::\d+)?$"


def host_to_csrf_origins(host: str) -> list[str]:
    host = host.strip()
    if not host or host == '*':
        return []
    if host.startswith('http://') or host.startswith('https://'):
        return [host]

    allow_subdomains = host.startswith('.')
    trimmed = host.lstrip('.')
    prefix = '*.' if allow_subdomains else ''
    return [f"http://{prefix}{trimmed}", f"https://{prefix}{trimmed}"]


def get_local_ip_candidates() -> list[str]:
    ips: set[str] = set()
    for env_key in ('LOCAL_IP_ADDRESSES', 'SERVER_IP', 'HOST_IP'):
        ips.update(str_to_list(os.getenv(env_key)))
    try:
        hostname = socket.gethostname()
        if hostname:
            host_ip = socket.gethostbyname(hostname)
            if host_ip:
                ips.add(host_ip)
            for family in (socket.AF_INET,):
                try:
                    for info in socket.getaddrinfo(hostname, None, family=family):
                        ip_addr = info[4][0]
                        if ip_addr:
                            ips.add(ip_addr)
                except OSError:
                    continue
    except OSError:
        pass
    ips.discard('127.0.0.1')
    ips.discard('0.0.0.0')
    return sorted(ips)


